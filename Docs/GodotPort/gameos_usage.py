#!/usr/bin/env python3
"""Inventory of the GameOS API surface that MechCommander 2 actually uses.

GameOS shipped as headers only (Source/GameOS/include). Everything the game
calls through GameOS.HPP / ToolOS.hpp has to be reimplemented for the Godot
port. This script lists those names, how often they are referenced, and which
libraries reference them, grouped by subsystem.

Usage:
    python3 Docs/GodotPort/gameos_usage.py > Docs/GodotPort/GameOS-API-Usage.md
"""

import collections
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCE = os.path.join(REPO, "Source")
HEADERS = ["GameOS.HPP", "ToolOS.hpp"]
SCAN_DIRS = ["Code", "MCLib", "GUI", "Editor", "Viewer", "ABLT", "Tools"]
SOURCE_EXTS = (".cpp", ".c", ".h", ".hpp", ".inl")

# Ordered (group, pattern) list; first match wins.
GROUPS = [
    ("Rendering", r"^gos_(SetRenderState|PushRenderStates|PopRenderStates|Draw\w+|RenderIndexedArray|SetupViewport|GetViewport|SetScreenMode)$"),
    ("Textures", r"^gos_(\w*Texture\w*)$"),
    ("Text and fonts", r"^gos_(Text\w+|LoadFont|DeleteFont)$"),
    ("Input", r"^(gos_(GetKey\w*|KeyboardFlush|DescribeKey|GetMouseInfo|SetMousePosition|\w*IME\w*)|gosJoystick_\w+)$"),
    ("Audio", r"^gosAudio_\w+$"),
    ("Video", r"^gosVideo_\w+$"),
    ("Files", r"^gos_(\w*File\w*|Find\w+|CreateDirectory|GetCurrentPath|GetDriveFreeSpace)$"),
    ("Memory", r"^gos_(Malloc|Free|\w*Heap\w*)$"),
    ("Time", r"^gos_(GetHiResTime|GetElapsedTime|GetFormatted\w+|GetTimeDate|GetUnformattedDate)$"),
    ("Networking", r"^gos_Net\w+$"),
    ("Debug and errors", r"^(gosASSERT|STOP|PAUSE|SPEW|InternalFunction\w+|ErrorHandler|AddStatistic|StatisticFormat|\w*CycleTiming|GetCycles|\w*DebuggerMenuItem)$"),
    ("System", r".*"),
]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def declared_api():
    names = {}
    for header in HEADERS:
        with open(os.path.join(SOURCE, "GameOS", "include", header), errors="ignore") as f:
            text = strip_comments(f.read())
        for m in re.finditer(r"\b(?:__stdcall|__cdecl)\s+(\w+)\s*\(", text):
            names.setdefault(m.group(1), header)
        for m in re.finditer(r"^\s*(?:extern\s+)?[\w:*&<> ]+?\s+\**(gos\w+)\s*\(", text, re.M):
            names.setdefault(m.group(1), header)
        for m in re.finditer(r"#define\s+(gos\w+|STOP|PAUSE|SPEW)\b", text):
            names.setdefault(m.group(1), header)
    return names


def library_of(path):
    rel = os.path.relpath(path, SOURCE).replace(os.sep, "/")
    parts = rel.split("/")
    if parts[0] == "MCLib" and len(parts) > 2:
        return "MCLib/" + parts[1]
    return parts[0]


def scan(api):
    word = re.compile(r"\b(" + "|".join(sorted(map(re.escape, api), key=len, reverse=True)) + r")\b")
    counts = collections.Counter()
    where = collections.defaultdict(set)
    for d in SCAN_DIRS:
        for root, _, files in os.walk(os.path.join(SOURCE, d)):
            for name in files:
                if not name.lower().endswith(SOURCE_EXTS):
                    continue
                path = os.path.join(root, name)
                with open(path, errors="ignore") as f:
                    text = strip_comments(f.read())
                for m in word.finditer(text):
                    counts[m.group(1)] += 1
                    where[m.group(1)].add(library_of(path))
    return counts, where


def group_of(name):
    for group, pattern in GROUPS:
        if re.match(pattern, name):
            return group
    return "System"


def main():
    api = declared_api()
    counts, where = scan(api)
    grouped = collections.defaultdict(list)
    for name, n in counts.items():
        grouped[group_of(name)].append((n, name))

    out = sys.stdout
    out.write("# GameOS API usage\n\n")
    out.write("Generated by `Docs/GodotPort/gameos_usage.py`. Do not edit by hand.\n\n")
    out.write(f"- Names declared in `{'`, `'.join(HEADERS)}`: {len(api)}\n")
    out.write(f"- Names referenced outside `Source/GameOS`: {len(counts)}\n")
    out.write(f"- Declared but never referenced: {len(api) - len(counts)}\n\n")
    out.write("Counts are textual references (calls, macro uses and declarations) with comments stripped.\n\n")
    out.write("| Group | Names used | References |\n|---|---:|---:|\n")
    order = [g for g, _ in GROUPS]
    for group in order:
        if group in grouped:
            out.write(f"| {group} | {len(grouped[group])} | {sum(n for n, _ in grouped[group])} |\n")
    for group in order:
        if group not in grouped:
            continue
        out.write(f"\n## {group}\n\n| Name | Refs | Referenced from |\n|---|---:|---|\n")
        for n, name in sorted(grouped[group], key=lambda x: (-x[0], x[1])):
            out.write(f"| `{name}` | {n} | {', '.join(sorted(where[name]))} |\n")
    unused = sorted(set(api) - set(counts))
    out.write("\n## Declared but unused\n\nThese do not need an implementation (a stub that fails loudly is enough).\n\n")
    out.write(", ".join(f"`{n}`" for n in unused) + "\n")


if __name__ == "__main__":
    main()
